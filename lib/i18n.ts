export type Dict = Record<keyof (typeof dictionary)["ar"], string>;

export function t(lang: Lang): Dict {
  return dictionary[lang];
}

export function dirOf(lang: Lang): "rtl" | "ltr" {
  return lang === "ar" ? "rtl" : "ltr";
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}

export function formatMoney(lang: Lang, value: number): string {
  return `${new Intl.NumberFormat("en-US", { maximumFractionDigits: 0 }).format(value)} ${t(lang).currency}`;
}

export function formatNumber(_lang: Lang, value: number): string {
  return new Intl.NumberFormat("en-US").format(value);
}
